import { chromium } from 'playwright-core';
import { readFile, mkdir, mkdtemp, rm, writeFile, copyFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import assert from 'node:assert/strict';
import { fixtureServer } from './fixtures.mjs';

// Surface the decisive browser failure in public Actions annotations without hiding its exit status.
process.on('uncaughtExceptionMonitor', error => {
  if (process.env.GITHUB_ACTIONS !== 'true') return;
  const message = String(error.stack || error.message).replaceAll('%', '%25').replaceAll('\r', '%0D').replaceAll('\n', '%0A');
  console.error(`::error title=Browser validation failed::${message}`);
});

await mkdir('artifacts', { recursive: true });
const source = await readFile('wipeditt.user.js', 'utf8');
const browser = await chromium.launch({ executablePath: process.env.WIPEDITT_CHROME || '/usr/bin/google-chrome', headless: true, args: ['--no-sandbox'] });
try {
  const context = await browser.newContext({ viewport: { width: 1280, height: 1000 } });
  const server = fixtureServer();
  await context.route('**/*', server.route);
  // Emulate userscript document-start injection, including the OAuth callback window.
  await context.addInitScript({ content: source });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('https://www.reddit.com/');
  await page.getByRole('button', { name: 'Open Wipeditt' }).click();
  await page.evaluate(source);
  assert.equal(await page.locator('#wipeditt-runtime-v1').count(), 1);
  assert.equal(await page.getByRole('button', { name: 'Scan history', exact: true }).isVisible(), false);
  assert.equal(await page.getByRole('button', { name: 'Try demo data', exact: true }).isVisible(), false);
  await page.locator('.panel').screenshot({ path: 'artifacts/connect.png' });
  const advanceUntil = async predicate => {
    for (let n = 0; n < 80; n++) {
      await new Promise(resolve => setTimeout(resolve, 250));
      if (await page.evaluate(predicate)) return;
    }
    throw new Error('Timed out waiting for fixture browser state');
  };
  await page.getByRole('button', { name: 'Connect Reddit', exact: true }).click();
  await page.getByRole('textbox', { name: 'Reddit Client ID', exact: true }).fill('fixture-client-id');
  await page.getByRole('button', { name: 'Sign in with Reddit', exact: true }).click();
  await advanceUntil(() => document.querySelector('#wipeditt-runtime-v1').shadowRoot.querySelector('.connection-name').textContent === 'u/fixture_user');
  assert.equal(server.edits(), 0);
  assert.equal(await page.evaluate(() => localStorage.getItem('wipeditt.clientId')), 'fixture-client-id');
  assert.ok(!await page.evaluate(() => JSON.stringify({ ...localStorage, ...sessionStorage })).then(text => text.includes('fixture-token')));
  await page.getByRole('button', { name: 'Scan history', exact: true }).click();
  await advanceUntil(() => document.querySelector('#wipeditt-runtime-v1').shadowRoot.querySelectorAll('.item').length === 2);
  assert.equal(await page.getByRole('checkbox', { name: 'Select t1_other', exact: true }).isDisabled(), true);
  assert.match(await page.locator('.counts').textContent(), /1 selected/);
  const callsBeforeReplacement = server.calls.length;
  const attack = '<img src=x onerror="window.INJECTED=true">';
  await page.locator('#replacement').fill(attack);
  assert.equal(await page.locator('.item').count(), 2, 'replacement changes must preserve the scan');
  assert.equal(server.calls.length, callsBeforeReplacement, 'replacement changes do not fetch history again');
  await page.getByRole('button', { name: 'Review 1 selected', exact: true }).click();
  assert.equal(await page.getByRole('button', { name: 'Cancel', exact: true }).evaluate(node => node === node.getRootNode().activeElement), true);
  assert.equal(await page.getByRole('dialog').locator('pre').textContent(), attack);
  assert.equal(await page.getByRole('dialog').locator('img').count(), 0);
  await page.keyboard.press('Escape');
  assert.equal(server.edits(), 0, 'closing confirmation cannot authorize writes');
  await page.getByRole('button', { name: 'Select none', exact: true }).click();
  assert.equal(await page.getByRole('button', { name: 'Review 0 selected', exact: true }).isDisabled(), true);
  await page.getByRole('button', { name: 'Select all', exact: true }).click();
  await page.locator('#replacement').fill('A fresh start.');
  const other = await context.newPage();
  await other.goto('https://www.reddit.com/');
  await other.evaluate(() => { navigator.locks.request('wipeditt.operation', async () => { window.lockReady = true; await new Promise(resolve => { window.releaseLock = resolve; }); }); });
  await other.waitForFunction(() => window.lockReady);
  await page.getByRole('button', { name: 'Review 1 selected', exact: true }).click();
  await page.getByRole('button', { name: 'Anonymize selected', exact: true }).click();
  await page.locator('.status').filter({ hasText: 'already running in another tab' }).waitFor();
  assert.equal(server.edits(), 0);
  await other.evaluate(() => window.releaseLock());
  await other.close();
  await page.getByRole('button', { name: 'Review 1 selected', exact: true }).click();
  await page.getByRole('button', { name: 'Anonymize selected', exact: true }).click();
  await page.getByRole('button', { name: 'Pause', exact: true }).click();
  await new Promise(resolve => setTimeout(resolve, 1000));
  assert.equal(server.edits(), 0);
  await page.getByRole('button', { name: 'Resume', exact: true }).click();
  await advanceUntil(() => document.querySelector('#wipeditt-runtime-v1').shadowRoot.querySelector('.status').textContent.includes('Finished'));
  assert.equal(server.edits(), 1);
  assert.equal(server.item.data.body, 'A fresh start.');
  assert.match(await page.locator('.status').textContent(), /1 anonymized/);
  await page.locator('.scope').evaluate(node => { node.open = true; });
  await page.getByText('Add filters', { exact: true }).click();
  await page.locator('#regex').fill('[');
  await page.getByRole('button', { name: 'Scan history', exact: true }).click();
  assert.match(await page.locator('.status').textContent(), /Invalid regular expression/);
  await page.locator('#regex').fill('');
  await page.getByRole('button', { name: 'Scan history', exact: true }).click();
  await advanceUntil(() => document.querySelector('#wipeditt-runtime-v1').shadowRoot.querySelectorAll('.item').length === 2);
  await page.locator('.panel').evaluate(node => { node.scrollTop = 0; });
  await page.locator('.panel').screenshot({ path: 'artifacts/panel-dark.png' });
  await page.getByText('Settings & help', { exact: true }).click();
  await page.getByRole('checkbox', { name: 'Privacy mode', exact: true }).check();
  assert.equal(await page.locator('.original').first().evaluate(node => getComputedStyle(node).filter), 'blur(6px)');
  await page.getByRole('checkbox', { name: 'Privacy mode', exact: true }).uncheck();
  await page.getByRole('button', { name: 'Light mode', exact: true }).click();
  await page.locator('.settings').evaluate(node => { node.open = false; });
  await page.locator('.panel').evaluate(node => { node.scrollTop = 0; });
  await page.locator('.panel').screenshot({ path: 'artifacts/panel-light.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.locator('.panel').evaluate(node => node.getBoundingClientRect().right <= innerWidth));
  await page.locator('.panel').screenshot({ path: 'artifacts/panel-mobile.png' });
  await page.getByRole('button', { name: 'Disconnect', exact: true }).click();
  assert.equal(await page.getByRole('button', { name: 'Connect Reddit', exact: true }).isVisible(), true);
  assert.deepEqual(errors, []);
  console.log(`Userscript browser passed · ${browser.version()} · complete OAuth callback/token exchange, HTTP scan/edit/verification, selection, confirmation, pause/resume, privacy and mobile. All HTTP responses were fixtures.`);
} finally { await browser.close(); }

const profile = await mkdtemp(join(tmpdir(), 'wipeditt-browser-'));
const extensionDir = join(profile, 'extension');
await mkdir(extensionDir);
let context;
try {
  const manifest = JSON.parse(await readFile('dist/chromium/manifest.json', 'utf8'));
  await writeFile(join(extensionDir, 'manifest.json'), JSON.stringify(manifest));
  for (const file of ['wipeditt.user.js', 'background.js', 'icon-48.png', 'icon-128.png']) await copyFile(`dist/chromium/${file}`, join(extensionDir, file));
  context = await chromium.launchPersistentContext(join(profile, 'profile'), { executablePath: process.env.WIPEDITT_EXTENSION_CHROME || chromium.executablePath(), headless: true, args: ['--no-sandbox', `--disable-extensions-except=${extensionDir}`, `--load-extension=${extensionDir}`] });
  const server = fixtureServer();
  await context.route('**/*', server.route);
  const page = await context.newPage();
  await page.goto('https://www.reddit.com/');
  await page.getByRole('button', { name: 'Open Wipeditt' }).waitFor();
  await page.evaluate(source);
  assert.equal(await page.locator('#wipeditt-runtime-v1').count(), 1);
  await page.getByRole('button', { name: 'Open Wipeditt' }).click();
  await page.getByRole('button', { name: 'Connect Reddit', exact: true }).click();
  await page.getByRole('textbox', { name: 'Reddit Client ID', exact: true }).fill('fixture-client-id');
  await page.getByRole('button', { name: 'Sign in with Reddit', exact: true }).click();
  await page.locator('.connection-name').filter({ hasText: 'u/fixture_user' }).waitFor({ timeout: 15000 });
  await page.getByRole('button', { name: 'Scan history', exact: true }).click();
  await page.locator('.item').first().waitFor({ timeout: 15000 });
  await page.locator('#replacement').fill('Extension fixture replacement.');
  await page.getByRole('button', { name: 'Review 1 selected', exact: true }).click();
  await page.getByRole('button', { name: 'Anonymize selected', exact: true }).click();
  await page.locator('.status').filter({ hasText: 'Finished' }).waitFor({ timeout: 30000 });
  assert.equal(server.edits(), 1);
  assert.equal(server.item.data.body, 'Extension fixture replacement.');
  assert.ok(server.calls.some(call => call.path === '/api/v1/access_token'));
  console.log(`Chromium extension passed · ${context.browser().version()} · actual content script and background broker; full OAuth, scan, guarded edit and verification using HTTP fixtures.`);
} finally { await context?.close(); await rm(profile, { recursive: true, force: true }); }
