import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
const pkg = JSON.parse(await readFile('package.json', 'utf8'));
const lock = JSON.parse(await readFile('package-lock.json', 'utf8'));
assert.equal(lock.version, pkg.version);
assert.equal(pkg.license, 'GPL-3.0-only');
assert.equal(pkg.build.mac, undefined);
assert.equal(pkg.main, 'app/main.cjs');
const version = JSON.parse(await readFile('app/version.json', 'utf8'));
assert.equal(version.version, pkg.version);
assert.equal(version.integration, 'native-browser');
for (const file of ['main.cjs', 'preload.cjs', 'renderer.js']) execFileSync(process.execPath, ['--check', `app/${file}`]);
assert.deepEqual(await readFile('app/LICENSE'), await readFile('LICENSE'));
assert.match(await readFile('app/index.html', 'utf8'), /connect-src 'none'/);
const main = await readFile('app/main.cjs', 'utf8');
assert.match(main, /nodeIntegration: false/);
assert.match(main, /contextIsolation: true/);
assert.match(main, /sandbox: true/);
assert.ok(!main.includes('GM_xmlhttpRequest'));
assert.ok(!main.includes('demo_user'), 'Production must not bundle the sample dataset.');
assert.ok(!(await readFile('app/index.html', 'utf8')).includes('Try sample data'));
assert.ok(!main.includes('api/v1/access_token'));
assert.deepEqual(await readFile('app/NOTICE'), await readFile('NOTICE'));
await readFile('app/icon.png');
console.log('Desktop versions, license, syntax, CSP, isolated browser preferences and retired OAuth path checks passed.');
